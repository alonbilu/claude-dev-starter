#!/usr/bin/env bash
# scripts/harden-server.sh — Baseline hardening for a fresh Ubuntu 22+ server.
#
# WHAT THIS DOES:
#   • Changes the SSH port (default 22 → 22222) — configurable
#   • Disables root login + password auth (key-only)
#   • Tightens sshd: MaxAuthTries, ClientAliveInterval
#   • Installs + configures ufw — default deny incoming, allow new SSH port + 80 + 443
#   • Installs + configures fail2ban — bans IPs after repeated failed SSH attempts
#   • Enables unattended-upgrades for automatic security patches
#   • OPTIONAL: installs lynis for an audit report
#
# RUN ON THE SERVER, AS ROOT (or via sudo).
#
# Safety:
#   • Asks before each step.
#   • Opens the new SSH port in ufw BEFORE restarting sshd, so you don't lock yourself out.
#   • Keeps the OLD SSH port open in ufw until you confirm you can reconnect on the new port.
#   • All actions are idempotent — safe to re-run.

set -euo pipefail

if [[ $EUID -ne 0 ]]; then
  echo "This script must run as root (or via sudo)."
  exit 1
fi

GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
NC='\033[0m'

ok()    { echo -e "${GREEN}✓${NC} $1"; }
info()  { echo -e "${YELLOW}→${NC} $1"; }
warn()  { echo -e "${RED}!${NC} $1"; }

echo ""
echo "============================================="
echo " Server Hardening"
echo "============================================="
echo ""
warn "Read each prompt carefully. The SSH-port step can lock you out if misconfigured."
echo ""

# ── Inputs ──────────────────────────────────────────────────────────────────
read -rp "New SSH port [22222]: " NEW_SSH_PORT
NEW_SSH_PORT=${NEW_SSH_PORT:-22222}
if ! [[ "$NEW_SSH_PORT" =~ ^[0-9]+$ ]] || (( NEW_SSH_PORT < 1024 || NEW_SSH_PORT > 65535 )); then
  warn "Invalid port. Must be 1024–65535. Aborting."
  exit 1
fi
read -rp "Path to a public SSH key to authorize (e.g. /tmp/your_key.pub) [skip]: " SSH_KEY_PATH
read -rp "Email for unattended-upgrades notifications (blank to skip notifications): " UPGRADE_EMAIL
read -rp "Install lynis for a security audit at the end? [y/N]: " RUN_LYNIS

echo ""
echo "Summary:"
echo "  SSH port:    22 → $NEW_SSH_PORT"
echo "  SSH key:     ${SSH_KEY_PATH:-(none — keep existing)}"
echo "  Upgrade mail: ${UPGRADE_EMAIL:-(disabled)}"
echo "  Run lynis:   ${RUN_LYNIS:-no}"
echo ""
read -rp "Proceed? [y/N]: " confirm
[[ "$confirm" =~ ^[Yy]$ ]] || { echo "Aborted."; exit 1; }

# ── Authorize a fresh SSH key (BEFORE locking down password auth) ───────────
if [[ -n "${SSH_KEY_PATH:-}" && -f "$SSH_KEY_PATH" ]]; then
  info "Authorizing SSH key from $SSH_KEY_PATH..."
  mkdir -p /root/.ssh
  chmod 700 /root/.ssh
  touch /root/.ssh/authorized_keys
  chmod 600 /root/.ssh/authorized_keys
  if ! grep -qxFf "$SSH_KEY_PATH" /root/.ssh/authorized_keys; then
    cat "$SSH_KEY_PATH" >> /root/.ssh/authorized_keys
    ok "SSH key authorized."
  else
    ok "SSH key already in authorized_keys."
  fi
fi

# ── Open the new SSH port in ufw FIRST (before sshd restart) ────────────────
info "Installing ufw..."
DEBIAN_FRONTEND=noninteractive apt-get install -y ufw >/dev/null
ufw allow "$NEW_SSH_PORT"/tcp comment 'new ssh port' >/dev/null
ufw allow 22/tcp comment 'old ssh port — REMOVE after confirming new port works' >/dev/null
ufw allow 80/tcp >/dev/null
ufw allow 443/tcp >/dev/null
ufw default deny incoming >/dev/null
ufw default allow outgoing >/dev/null
yes | ufw enable >/dev/null
ok "ufw enabled. Ports open: $NEW_SSH_PORT, 22 (TEMPORARY), 80, 443."

# ── Harden sshd ──────────────────────────────────────────────────────────────
info "Hardening /etc/ssh/sshd_config..."
SSHD_CONFIG=/etc/ssh/sshd_config
cp "$SSHD_CONFIG" "${SSHD_CONFIG}.bak.$(date +%s)"

# Use a drop-in to avoid wrestling with existing edits.
cat > /etc/ssh/sshd_config.d/99-hardening.conf <<EOF
# Generated by scripts/harden-server.sh — do not edit by hand.
Port $NEW_SSH_PORT
PermitRootLogin prohibit-password
PasswordAuthentication no
ChallengeResponseAuthentication no
KbdInteractiveAuthentication no
PubkeyAuthentication yes
PermitEmptyPasswords no
MaxAuthTries 3
ClientAliveInterval 300
ClientAliveCountMax 2
X11Forwarding no
AllowAgentForwarding no
AllowTcpForwarding no
LoginGraceTime 30
EOF

sshd -t && systemctl reload ssh
ok "sshd hardened. Port: $NEW_SSH_PORT; password auth: off; root password login: off."
echo ""
warn "IMPORTANT — TEST THE NEW PORT BEFORE CLOSING THE OLD ONE:"
warn "  Open a NEW terminal and run: ssh -p $NEW_SSH_PORT root@<this-server-ip>"
warn "  Once verified, remove the legacy port: ufw delete allow 22/tcp"
echo ""

# ── fail2ban ─────────────────────────────────────────────────────────────────
info "Installing fail2ban..."
DEBIAN_FRONTEND=noninteractive apt-get install -y fail2ban >/dev/null
cat > /etc/fail2ban/jail.local <<EOF
[DEFAULT]
bantime  = 3600
findtime = 600
maxretry = 5
banaction = ufw

[sshd]
enabled = true
port    = $NEW_SSH_PORT,22
filter  = sshd
backend = systemd
EOF
systemctl enable --now fail2ban >/dev/null
systemctl restart fail2ban
ok "fail2ban installed. SSH jail active — 5 failed attempts → 1h ban."

# ── Unattended security upgrades ─────────────────────────────────────────────
info "Enabling unattended-upgrades..."
DEBIAN_FRONTEND=noninteractive apt-get install -y unattended-upgrades apt-listchanges >/dev/null
cat > /etc/apt/apt.conf.d/20auto-upgrades <<'EOF'
APT::Periodic::Update-Package-Lists "1";
APT::Periodic::Unattended-Upgrade "1";
APT::Periodic::AutocleanInterval "7";
EOF

if [[ -n "${UPGRADE_EMAIL:-}" ]]; then
  sed -i "s|//Unattended-Upgrade::Mail .*|Unattended-Upgrade::Mail \"$UPGRADE_EMAIL\";|" \
    /etc/apt/apt.conf.d/50unattended-upgrades 2>/dev/null || true
fi
ok "unattended-upgrades enabled — security patches auto-applied daily."

# ── Optional: lynis audit ────────────────────────────────────────────────────
if [[ "${RUN_LYNIS:-}" =~ ^[Yy]$ ]]; then
  info "Installing lynis..."
  DEBIAN_FRONTEND=noninteractive apt-get install -y lynis >/dev/null
  echo ""
  echo "Running lynis audit (may take a few minutes)..."
  lynis audit system --quick --no-colors | tail -40
  echo ""
  ok "Lynis report: /var/log/lynis.log"
fi

# ── Summary ──────────────────────────────────────────────────────────────────
echo ""
echo "============================================="
echo " Hardening complete."
echo "============================================="
echo ""
echo "What was applied:"
echo "  • SSH on port $NEW_SSH_PORT (port 22 still open — REMOVE after confirming)"
echo "  • Password auth disabled — key-only logins"
echo "  • Root login restricted to keys"
echo "  • ufw: deny incoming default; allow $NEW_SSH_PORT, 80, 443"
echo "  • fail2ban: 5 failed attempts → 1h ban"
echo "  • unattended-upgrades: daily security patches"
if [[ "${RUN_LYNIS:-}" =~ ^[Yy]$ ]]; then
  echo "  • Lynis audit report at /var/log/lynis.log"
fi
echo ""
echo "Next steps:"
echo "  1. Open a NEW terminal and verify SSH on the new port:"
echo "       ssh -p $NEW_SSH_PORT root@<server-ip>"
echo "  2. Once that works, close port 22:"
echo "       ufw delete allow 22/tcp"
echo "  3. Set up your apps (e.g. scripts/staging-setup.sh)."
echo ""
